#[test]
fn test_fft_bitwise_determinism_large() {
    // Two identically-configured FFT models must produce bit-identical output.
    let weights: Vec<f32> = (0..2048)
        .map(|i| (i as f32 * 0.005).sin() * (-i as f32 * 0.0005).exp())
        .collect();
    let bias = 0.1;
    let input = synth_multi_freq_signal(4096, &mut SimplePcg::new(42));

    let mut model1 = StaticModel::Linear(Box::new(
        LinearModel::new(weights.clone(), bias, LinearImplementation::Fft).unwrap(),
    ));
    let mut model2 = StaticModel::Linear(Box::new(
        LinearModel::new(weights, bias, LinearImplementation::Fft).unwrap(),
    ));

    model1.prewarm(input.len());
    model2.prewarm(input.len());

    let mut out1 = vec![0.0f32; input.len()];
    let mut out2 = vec![0.0f32; input.len()];
    model1.process(&input, &mut out1);
    model2.process(&input, &mut out2);

    assert_eq!(out1.len(), out2.len());
    for (i, (a, b)) in out1.iter().zip(out2.iter()).enumerate() {
        assert!(
            (a - b).abs() < 1e-10,
            "bitwise determinism failed at sample {i}: {a} vs {b}"
        );
    }
}

#[test]
fn test_fft_reset_reproduces() {
    // Reset must restore exact initial state — output must be reproducible.
    let weights: Vec<f32> = (0..2048)
        .map(|i| (i as f32 * 0.005).sin() * (-i as f32 * 0.0005).exp())
        .collect();
    let bias = 0.05;
    let input = synth_multi_freq_signal(4096, &mut SimplePcg::new(99));
    let reference = linear_oracle(&input, &weights, bias);

    let mut model = StaticModel::Linear(Box::new(
        LinearModel::new(weights, bias, LinearImplementation::Fft).unwrap(),
    ));
    model.prewarm(input.len());
    let mut out1 = vec![0.0f32; input.len()];
    model.process(&input, &mut out1);

    model.reset(48000, 8192).unwrap();
    model.prewarm(input.len());
    let mut out2 = vec![0.0f32; input.len()];
    model.process(&input, &mut out2);

    for (i, ((vr, o1), o2)) in reference
        .iter()
        .zip(out1.iter())
        .zip(out2.iter())
        .enumerate()
    {
        assert!(
            (o1 - o2).abs() < 1e-6,
            "reset-reproduce mismatch between runs at sample {i}: {o1:.8e} vs {o2:.8e}"
        );
        assert!(
            (o1 - vr).abs() < 1e-4,
            "reset-reproduce: out1 diverged from oracle at sample {i}: {o1:.8e} vs {vr:.8e}"
        );
    }
}

