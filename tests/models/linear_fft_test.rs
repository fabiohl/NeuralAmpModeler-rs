#[test]
fn test_fft_golden_rf2048_sine_short() {
    let input = generate_sine_440hz(GOLDEN_NUM_SAMPLES);
    let rng = &mut SimplePcg::new(42);
    let weights: Vec<f32> = (0..2048)
        .map(|i| {
            let x = i as f32 / 2048.0;
            (std::f32::consts::TAU * 3.0 * x).cos() * (-2.0 * x).exp() * 0.9
                + 0.005 * rng.next_f32_signed()
        })
        .collect();
    verify_against_oracle("Linear FFT RF=2048 sine", &weights, 0.1, &input);
}

