/// Loads a .nam model file through the full dispatcher pipeline, processes the
/// input, and validates against the direct FIR oracle.
fn verify_nam_file_against_oracle(nam_filename: &str, label: &str, input: &[f32]) {
    let nam_path = model_path(nam_filename);
    assert!(
        nam_path.exists(),
        "Fixture model {nam_filename} not found at {nam_path:?}"
    );

    let json_data =
        fs::read_to_string(&nam_path).unwrap_or_else(|_| panic!("Failed to read {nam_filename}"));
    let model_data =
        parse_nam_json(&json_data).unwrap_or_else(|_| panic!("Failed to parse {nam_filename}"));
    let mut model =
        build_model(&model_data).unwrap_or_else(|_| panic!("Dispatcher failed for {nam_filename}"));

    // Extract weights and bias from the model for oracle computation.
    // The dispatcher loads weights in forward-time order from JSON.
    let weights: Vec<f32> = model_data
        .weights
        .iter()
        .take(model_data.weights.len().saturating_sub(1))
        .copied()
        .collect();
    let bias = model_data.weights.last().copied().unwrap_or(0.0);

    let reference = linear_oracle(input, &weights, bias);

    model.prewarm(input.len());
    let mut output = vec![0.0f32; input.len()];
    process_in_blocks(&mut model, input, &mut output, GOLDEN_BLOCK_SIZE);

    report_dsp_fidelity_no_lufs(
        &reference,
        &output,
        Some(1e-6),
        60.0,
        Some(1e-6),
        Some(0.12),
        label,
        48000,
    );
}

#[test]
fn test_fft_fixture_rf320_loader_pipeline() {
    let input = generate_sine_440hz(2048);
    verify_nam_file_against_oracle(
        "linear_fft_rf320.nam",
        "FFT fixture RF=320 (loader pipeline)",
        &input,
    );
}

