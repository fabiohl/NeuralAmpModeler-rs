// ══════════════════════════════════════════════════════════════════════════════
// Deterministic PRNG (compatible with linear_golden.rs)
// ══════════════════════════════════════════════════════════════════════════════

struct SimplePcg {
    state: u64,
    inc: u64,
}

impl SimplePcg {
    fn new(seed: u64) -> Self {
        Self {
            state: seed.wrapping_add(1442695040888963407),
            inc: 1,
        }
    }

    fn next_f32(&mut self) -> f32 {
        let old_state = self.state;
        self.state = old_state
            .wrapping_mul(6364136223846793005)
            .wrapping_add(self.inc | 1);
        let xorshifted = (((old_state >> 18) ^ old_state) >> 27) as u32;
        let rot = (old_state >> 59) as u32;
        let rotated = (xorshifted >> rot) | (xorshifted << ((-(rot as i32)) & 31));
        (rotated as f32) * 2.3283064e-10
    }

    fn next_f32_signed(&mut self) -> f32 {
        self.next_f32() * 2.0 - 1.0
    }
}

// ══════════════════════════════════════════════════════════════════════════════
// Mathematical Oracle: Direct FIR Convolution (= C++ Linear DSP reference)
// ══════════════════════════════════════════════════════════════════════════════

fn linear_oracle(input: &[f32], weights_forward: &[f32], bias: f32) -> Vec<f32> {
    let r = weights_forward.len();
    if r == 0 {
        return vec![bias; input.len()];
    }
    let mut output = vec![0.0f32; input.len()];
    for n in 0..input.len() {
        let mut sum = 0.0f32;
        let max_k = n.min(r - 1);
        for k in 0..=max_k {
            sum += weights_forward[k] * input[n - k];
        }
        output[n] = bias + sum;
    }
    output
}

// ══════════════════════════════════════════════════════════════════════════════
// Signal synthesis
// ══════════════════════════════════════════════════════════════════════════════

fn synth_multi_freq_signal(len: usize, rng: &mut SimplePcg) -> Vec<f32> {
    (0..len)
        .map(|i| {
            let t = i as f32 / 48000.0;
            0.45 * (std::f32::consts::TAU * 110.0 * t).sin()
                + 0.30 * (std::f32::consts::TAU * 440.0 * t).sin()
                + 0.15 * (std::f32::consts::TAU * 880.0 * t).sin()
                + 0.03 * rng.next_f32_signed()
        })
        .collect()
}

// ══════════════════════════════════════════════════════════════════════════════
// Helper: run model + compare against oracle
// ══════════════════════════════════════════════════════════════════════════════

fn verify_against_oracle(label: &str, weights_forward: &[f32], bias: f32, input: &[f32]) {
    let reference = linear_oracle(input, weights_forward, bias);

    let mut model = StaticModel::Linear(Box::new(
        LinearModel::new(weights_forward.to_vec(), bias, LinearImplementation::Fft)
            .expect("Linear model creation"),
    ));
    model.prewarm(input.len());
    let mut output = vec![0.0f32; input.len()];
    model.process(input, &mut output);

    // Use ESR as primary gate (scale-invariant, robust for FFT precision).
    // LUFS plausibility gate is disabled — IR convolution with large weights
    // legitimately produces output above +10 LUFS (same pattern as cabsim goldens).
    // MR-STFT gate: 0.12 (calibrated from worst-case impulse response, S3.T04).
    report_dsp_fidelity_no_lufs(
        &reference,
        &output,
        Some(1e-6),
        60.0,
        Some(1e-6),
        Some(0.12),
        label,
        48000,
    );
}

