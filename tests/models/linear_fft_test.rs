//  Golden tests for the Linear FFT partitioned convolution engine.
//
//  Validates the zero-latency FFT hybrid convolution (`LinearFftState`) against
//  the direct time-domain FIR convolution mathematical oracle. The direct FIR
//  convolution is identical to the C++ `nam::Linear` reference implementation
//  in `NeuralAmpModelerCore/NAM/dsp.cpp:255-301`.
//
//  ## Test strategy
//
//  - **Mathematical oracle tests** (fast, always run): Load `.nam` models with
//    long receptive fields (320, 2048, 4096, 8192 taps) via the full loader
//    pipeline, process deterministic test signals, and validate against the
//    direct FIR convolution oracle. The FFT engine must produce outputs
//    identical to the C++ time-domain reference within f32 floating-point
//    tolerance (ESR < 1e-6, SNR > 60 dB).
//
//  - **C++ golden vector cross-reference**: Compare
//    NeuralAmpModeler-rs output against pre-rendered `.golden.bin` files generated by
//    the C++ `NeuralAmpModelerCore` render tool. Requires running
//    `./tests/fixtures/golden_gen_build.sh` with Linear FFT models included.
//    Tests skip gracefully if golden files are not present.
//
//  ## Fixture models
//
//  | File                               | RF    | Partitions | Partition size P |
//  |------------------------------------|-------|-----------|-------------------|
//  | `linear_fft_rf320.nam`             | 320   | 2         | 128               |
//  | `linear_fft_rf2048.nam`            | 2048  | 1         | 1024              |
//  | `linear_fft_rf4096.nam`            | 4096  | 1         | 2048              |
//  | `linear_fft_rf8192.nam`            | 8192  | 1         | 4096              |

