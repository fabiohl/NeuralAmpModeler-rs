/// Runs a golden `.bin` test for a Linear FFT model.
///
/// Requires the `.golden.bin` file to exist in `tests/fixtures/`. Gracefully
/// skips if the file is not present (goldens must be generated via
/// `./tests/fixtures/golden_gen_build.sh`).
fn run_fft_golden_bin_test(model_filename: &str, golden_filename: &str, label: &str) {
    let fixtures_dir = PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("tests/fixtures");
    let nam_path = model_path(model_filename);
    let golden_path = fixtures_dir.join(golden_filename);

    if !nam_path.exists() {
        eprintln!("SKIP: Model {model_filename} not found. Skipping golden bin test '{label}'.");
        return;
    }

    if !golden_path.exists() {
        eprintln!(
            "SKIP: Golden file {golden_filename} not found at {golden_path:?}.\n\
             Run './tests/fixtures/golden_gen_build.sh' to generate Linear FFT golden vectors."
        );
        return;
    }

    let (input, expected) = common::io_helpers::read_golden_bin(&golden_path)
        .unwrap_or_else(|| panic!("Failed to read {golden_filename}"));

    let json_data = fs::read_to_string(&nam_path).expect("Failed to read Linear FFT model JSON");
    let model_data = parse_nam_json(&json_data).expect("Failed to parse Linear FFT model JSON");
    let mut model = build_model(&model_data)
        .unwrap_or_else(|_| panic!("Dispatcher failed for {model_filename}"));

    model.prewarm(GOLDEN_NUM_SAMPLES);
    let mut output = vec![0.0f32; input.len()];
    process_in_blocks(&mut model, &input, &mut output, GOLDEN_BLOCK_SIZE);

    let (mse_limit, min_snr_db, max_esr, mrstft_max) =
        common::validation::topology_thresholds(&model_data, model_filename);
    report_dsp_fidelity(
        &expected, &output, mse_limit, min_snr_db, max_esr, mrstft_max, label, 48000,
    );
}

