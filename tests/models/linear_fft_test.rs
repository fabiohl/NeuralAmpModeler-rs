// Cross-block boundary tests — ensure FFT tail computation is seamless
// ══════════════════════════════════════════════════════════════════════════════

#[test]
fn test_fft_seamless_block_boundary() {
    // Process exactly P samples, then verify the output for the next P samples.
    // The FFT tail must be seamless across block boundaries.
    let p = 256; // partition size for RF=512: P = 256
    let weights: Vec<f32> = (0..512)
        .map(|i| (i as f32 * 0.01).sin() * (-i as f32 * 0.002).exp())
        .collect();
    let bias = 0.0;

    let ref_input: Vec<f32> = (0..2048)
        .map(|i| (i as f32 * 0.05).sin() * 0.5 + (i as f32 * 0.13).cos() * 0.3)
        .collect();
    let reference = linear_oracle(&ref_input, &weights, bias);

    let mut model = StaticModel::Linear(Box::new(
        LinearModel::new(weights, bias, LinearImplementation::Fft).unwrap(),
    ));
    model.prewarm(ref_input.len());
    let mut output = vec![0.0f32; ref_input.len()];
    model.process(&ref_input, &mut output);

    // Check each sample, highlighting block boundaries
    let mut max_diff = 0.0f32;
    let mut max_diff_idx = 0;
    for (i, (r, o)) in reference.iter().zip(output.iter()).enumerate() {
        let diff = (o - r).abs();
        if diff > max_diff {
            max_diff = diff;
            max_diff_idx = i;
        }
        if i > 0 && i % p == 0 {
            assert!(
                diff < 1e-3,
                "block boundary mismatch at sample {i} (P={p}): diff={diff:.2e}, ref={r:.6e}, out={o:.6e}"
            );
        }
    }
    assert!(
        max_diff < 1e-3,
        "max sample diff {max_diff:.2e} at idx {max_diff_idx} exceeds tolerance"
    );
}

#[test]
fn test_fft_long_seamless_boundaries() {
    // Multi-block seamless test with RF=2048 (P=1024, 2 partitions).
    // Verifies that the FFT tail reads from the correct sample_counter position
    // across multiple block computations.
    let weights: Vec<f32> = (0..2048)
        .map(|i| {
            let x = i as f32 / 2048.0;
            (std::f32::consts::TAU * 2.0 * x).cos() * (-1.5 * x).exp() * 0.8
        })
        .collect();
    let bias = 0.02;

    let num_samples = 16384;
    let rng = &mut SimplePcg::new(12345);
    let input: Vec<f32> = (0..num_samples)
        .map(|_| rng.next_f32_signed() * 0.5)
        .collect();
    let reference = linear_oracle(&input, &weights, bias);

    let mut model = StaticModel::Linear(Box::new(
        LinearModel::new(weights, bias, LinearImplementation::Fft).unwrap(),
    ));
    model.prewarm(input.len());
    let mut output = vec![0.0f32; input.len()];
    model.process(&input, &mut output);

    let mut max_diff = 0.0f32;
    for (r, o) in reference.iter().zip(output.iter()) {
        let diff = (o - r).abs();
        if diff > max_diff {
            max_diff = diff;
        }
    }

    let sum_sq_err: f64 = reference
        .iter()
        .zip(output.iter())
        .map(|(r, o)| (*r as f64 - *o as f64).powi(2))
        .sum();
    let sum_sq_ref: f64 = reference.iter().map(|r| (*r as f64).powi(2)).sum();
    let esr = sum_sq_err / sum_sq_ref;

    println!("\n[Linear FFT block-boundary validation — RF=2048 P=1024 16 blocks]");
    println!("  ESR    = {esr:.4e}");
    println!("  MaxErr = {max_diff:.2e}");
    println!("  Samples = {num_samples} @ 48 kHz");

    assert!(
        esr < 1e-6,
        "seamless block boundary ESR={esr:.4e} exceeds threshold 1e-6"
    );
}

